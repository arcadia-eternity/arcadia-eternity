import { createHash } from 'node:crypto'
import { createReadStream } from 'node:fs'
import { createRequire } from 'node:module'
import { copyFile, readFile, realpath } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { sha256Hex } from '@arcadia-eternity/const'
import { stageCatalogProject, withShippedCatalogArchive } from '@arcadia-eternity/pack-loader/node'
import { satisfies, validRange } from 'semver'
import { isRecord, errorCode } from './types.ts'

const officialBase = '@arcadia-eternity/data-pack-base'
const candidateArchive = /^file:candidates\/[a-zA-Z0-9_.-]+\.tgz$/

// The standalone SDK need not ship the official catalog. Prefer an available matching
// version when there is no registry pin. A registry lock always retains its own integrity.
async function baseDirectory(root: string, range: string, pinned?: string): Promise<string | undefined> {
  for (const loader of [createRequire(join(root, 'package.json')), createRequire(import.meta.url)]) {
    let file: string
    try {
      file = loader.resolve(officialBase + '/package.json')
    } catch (error) {
      if (errorCode(error) !== 'MODULE_NOT_FOUND') throw error
      continue
    }
    const { name, version } = JSON.parse(await readFile(file, 'utf8'))
    if (name === officialBase && satisfies(version, range) && (!pinned || version === pinned)) return dirname(file)
  }
  return undefined
}

async function matchesIntegrity(file: string, integrity: string) {
  const tokens = integrity.split(/\s+/)
  for (const algorithm of ['sha512', 'sha384', 'sha256', 'sha1']) {
    const expected = tokens.filter(token => token.startsWith(algorithm + '-'))
    if (!expected.length) continue
    const hash = createHash(algorithm)
    for await (const chunk of createReadStream(file)) hash.update(chunk)
    return expected.includes(algorithm + '-' + hash.digest('base64'))
  }
  throw new Error('INSTALL_LOCK_INTEGRITY_INVALID')
}

export async function stageEnvironmentDependencies({
  materialRoot,
  sourceRoot,
  installation,
  dependencies,
  hasSources,
  lockText,
  sourceLocked,
}: {
  materialRoot: string
  sourceRoot: string
  installation: string
  dependencies: Record<string, string>
  hasSources: boolean
  lockText?: string
  sourceLocked: boolean
}) {
  const root = await realpath(materialRoot)
  const lock = lockText ? JSON.parse(lockText) : undefined
  if (lock && (![2, 3].includes(lock.lockfileVersion) || !isRecord(lock.packages)))
    throw new Error('INSTALL_LOCK_INVALID')
  const local = new Set<string>()
  const locations = new Map<string, Array<{ location: string; integrity?: string }>>()
  for (const [name, spec] of Object.entries(dependencies)) {
    if (candidateArchive.test(spec)) local.add(spec)
    else if (!validRange(spec)) throw new Error(`INSTALL_VERSION_INVALID: ${name}`)
  }
  const requiredArchives = new Set(local)
  const basePin = lock?.packages['node_modules/' + officialBase]
  const localBasePin =
    typeof basePin?.resolved === 'string' && /^file:candidates\/debug-base-[a-f0-9]{64}\.tgz$/.test(basePin.resolved)
  const range = dependencies[officialBase]
  const bundled =
    range && validRange(range) && (!basePin?.resolved || localBasePin)
      ? await baseDirectory(
          sourceRoot,
          range,
          basePin && satisfies(basePin.version, range) ? basePin.version : undefined,
        )
      : undefined
  if (localBasePin && range && validRange(range) && satisfies(basePin.version, range) && !bundled)
    throw new Error(
      `BASE_PACK_VERSION_UNAVAILABLE: install ${officialBase}@${basePin.version} or regenerate the debug lock to use a registry artifact`,
    )
  for (const [location, entry] of Object.entries(lock?.packages ?? {})) {
    if (
      !isRecord(entry) ||
      entry.link ||
      (location &&
        (!location.startsWith('node_modules/') || location.includes('\\') || location.split('/').includes('..')))
    )
      throw new Error('INSTALL_LOCK_INVALID')
    if (typeof entry.resolved !== 'string') continue
    if (candidateArchive.test(entry.resolved)) {
      // Locally staged source archives and the local base are regenerated by the debug host.
      if (entry.resolved === basePin?.resolved && localBasePin) continue
      if (/^file:candidates\/[a-f0-9]{40}\.tgz$/.test(entry.resolved) && !local.has(entry.resolved)) continue
      local.add(entry.resolved)
      const pins = locations.get(entry.resolved) ?? []
      pins.push({ location, integrity: typeof entry.integrity === 'string' ? entry.integrity : undefined })
      locations.set(entry.resolved, pins)
    } else {
      const url = new URL(entry.resolved)
      if (url.protocol !== 'https:' || url.username || url.password) throw new Error('INSTALL_LOCK_INVALID')
    }
  }
  if (bundled && Object.keys(dependencies).length === 1 && !hasSources)
    return { installed: await stageCatalogProject(installation, bundled), lockText }
  for (const spec of local) {
    const relative = spec.slice(5)
    const file = join(root, relative)
    const pins = locations.get(spec) ?? []
    const canonical = await realpath(file).catch(error => {
      if (errorCode(error) !== 'ENOENT' || sourceLocked || requiredArchives.has(spec)) throw error
    })
    if (!canonical) {
      // A previous preview can still mention an archive the author removed or renamed.
      // Let npm resolve the current declarations without that obsolete local pin.
      for (const pin of pins) delete lock.packages[pin.location]
      continue
    }
    if (canonical !== file) throw new Error('MATERIAL_PATH_ESCAPE')
    const captured = join(installation, relative)
    await copyFile(file, captured)
    for (const pin of pins) {
      if (!pin.integrity || (await matchesIntegrity(captured, pin.integrity))) continue
      if (sourceLocked) throw new Error(`ENVIRONMENT_ARCHIVE_INTEGRITY: ${relative} differs from package-lock.json`)
      // npm may serve the old byte stream from its cache even for a changed file:
      // dependency. Discard this generated resolution and resolve the captured bytes.
      delete lock.packages[pin.location]
    }
  }
  if (bundled) {
    await withShippedCatalogArchive(bundled, undefined, async file => {
      const relative = 'candidates/debug-base-' + sha256Hex(await readFile(file)) + '.tgz'
      await copyFile(file, join(installation, relative))
      dependencies[officialBase] = 'file:' + relative
    })
  }
  return { lockText: lock && JSON.stringify(lock) }
}
