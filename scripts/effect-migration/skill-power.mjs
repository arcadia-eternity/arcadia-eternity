import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import { parse } from 'yaml'
import { format, resolveConfig } from 'prettier'
import { fields, normalize, condition, selectedNumber } from './authoring-emitter.mjs'

/** C07: explicit selector spelling repair on a copy; records every changed source node. */
export function repairSkillSelector(definition) {
  const paths = []
  function visit(v, path = '') {
    if (Array.isArray(v)) return v.map((x, i) => visit(x, `${path}/${i}`))
    if (v && typeof v === 'object')
      return Object.fromEntries(
        Object.entries(v).map(([k, x]) => {
          const next = `${path}/${k.replaceAll('~', '~0').replaceAll('/', '~1')}`
          if (['base', 'target'].includes(k) && x === 'useSkillContext') {
            paths.push(next)
            return [k, 'usingSkillContext']
          }
          return [k, visit(x, next)]
        }),
      )
    return v
  }
  return { definition: visit(definition), paths }
}
export function classifySkillPower(original) {
  if (!original || typeof original !== 'object' || Array.isArray(original)) return { reason: 'invalid definition' }
  const { definition: d, paths } = repairSkillSelector(original)
  if (
    !fields(d, [
      'id',
      'trigger',
      'priority',
      ...('condition' in d ? ['condition'] : []),
      'apply',
      ...['tags', 'consumesStacks'].filter(k => Object.hasOwn(d, k)),
    ]) ||
    typeof d.id !== 'string' ||
    !d.id ||
    !Number.isFinite(d.priority)
  )
    return { reason: 'unsupported definition fields' }
  if (!['BeforeUseSkillCheck', 'AfterUseSkillCheck', 'BeforeHit'].includes(d.trigger))
    return { reason: 'unsupported skill stage' }
  if ('consumesStacks' in d && (!Number.isSafeInteger(d.consumesStacks) || d.consumesStacks < 0))
    return { reason: 'invalid stack consumption' }
  if ('tags' in d && (!Array.isArray(d.tags) || !d.tags.every(x => typeof x === 'string')))
    return { reason: 'invalid tags' }
  const a = d.apply
  if (!fields(a, ['type', 'target', 'value']) || !['addPower', 'amplifyPower'].includes(a.type))
    return { reason: 'unsupported power action' }
  if (a.target !== 'usingSkillContext' && !(fields(a.target, ['base']) && a.target.base === 'usingSkillContext'))
    return { reason: 'unsupported target chain' }
  const amount = Number.isFinite(a.value) ? a.value : undefined
  const value =
    fields(a.value, ['type', 'selector']) && a.value.type === 'dynamic'
      ? selectedNumber(a.value.selector, undefined, undefined, 'all', 'skill')
      : undefined
  if (amount === undefined && !value) return { reason: 'unsupported power value' }
  const when = 'condition' in d ? condition(d.condition, 'skill') : '() => true'
  if (!when) return { reason: 'condition needs a separate mapping' }
  return {
    id: d.id,
    trigger: d.trigger,
    priority: d.priority,
    operation: a.type,
    ...(amount !== undefined ? { amount } : { value }),
    when,
    repairedPaths: paths,
    ...('consumesStacks' in d ? { consumesStacks: d.consumesStacks } : {}),
    ...('tags' in d ? { tags: d.tags } : {}),
  }
}
export async function generateSkillPower({ check = false } = {}) {
  const records = [],
    rejected = [],
    seen = new Set()
  for (const name of ['global', 'ability', 'emblem', 'mark', 'skill']) {
    const sourceFile = `packs/base/data/effect_${name}.yaml`
    for (const [index, d] of parse(await readFile(sourceFile, 'utf8'), { merge: true }).entries()) {
      if (seen.has(d.id)) throw new Error(`Duplicate effect ${d.id}`)
      seen.add(d.id)
      if (!['addPower', 'amplifyPower'].includes(d.apply?.type)) continue
      const source = {
        id: d.id,
        sourceFile,
        sourcePath: `/${index}`,
        definitionSha256: createHash('sha256')
          .update(JSON.stringify(normalize(d)))
          .digest('hex'),
      }
      const recipe = classifySkillPower(d)
      if (recipe.reason) rejected.push({ ...source, reason: recipe.reason })
      else
        records.push({
          ...source,
          recipe,
          classification: 'C',
          decision: 'C07',
          ...(/conditions\.(firstSkillThisTurn|lastSkillThisTurn)/.test(recipe.when)
            ? { additionalDecisions: ['C08'] }
            : {}),
          status: 'generated-correction-candidate',
        })
    }
  }
  records.sort((a, b) => a.id.localeCompare(b.id, 'en'))
  rejected.sort((a, b) => a.id.localeCompare(b.id, 'en'))
  const q = JSON.stringify
  const entries = records.map(
    ({ recipe: r }) =>
      `${q(r.id)}:compileEffect(defineEffect({id:${q(r.id)},on:${q(r.trigger)},priority:${r.priority},${r.consumesStacks !== undefined ? `consumesStacks:${r.consumesStacks},` : ''}${r.tags ? `tags:${q(r.tags)},` : ''}when:${r.when},execute:contexts.skillUse.apply(ops.${r.operation}(${r.value ?? r.amount}))}))`,
  )
  const code = `// Generated by scripts/effect-migration/skill-power.mjs. C07 correction candidates only.\nimport {compileEffect,defineEffect,conditions,contexts,targets,checks,ops,${entries.some(entry => entry.includes('values.')) ? 'values,' : ''}type EffectFrame} from '../content/authoring'\nexport function createGeneratedSkillPowerEffects(){return Object.freeze({${entries.join(',\n')}})}\nexport const generatedSkillPowerEffects=createGeneratedSkillPowerEffects()\n`
  for (const [path, raw] of [
    ['packages/battle/src/v4/official/skill-power.generated.ts', code],
    ['docs/v4/validation/skill-power-candidates.json', JSON.stringify({ formatVersion: 1, records, rejected })],
  ]) {
    const output = await format(raw, { ...(await resolveConfig(path)), filepath: path })
    if (check) {
      if ((await readFile(path, 'utf8')) !== output) throw new Error(`Generated drift: ${path}`)
    } else await writeFile(path, output)
  }
  return { generated: records.length, rejected: rejected.length }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.slice(2).some(a => a !== '--check')) throw new Error('Only --check supported')
  console.log(JSON.stringify(await generateSkillPower({ check: process.argv.includes('--check') })))
}
