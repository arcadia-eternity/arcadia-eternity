import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import { parse } from 'yaml'
import { format, resolveConfig } from 'prettier'

const canonical = value => JSON.stringify(normalize(value))
function normalize(value) {
  if (Array.isArray(value)) return value.map(normalize)
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(key => [key, normalize(value[key])]),
    )
  return value
}
const exact = (value, keys) =>
  value &&
  typeof value === 'object' &&
  !Array.isArray(value) &&
  Object.keys(value).sort().join(',') === [...keys].sort().join(',')
const selfCondition = condition =>
  (exact(condition, ['type']) && condition.type === 'selfUseSkill') ||
  (exact(condition, ['type', 'conditions']) &&
    condition.type === 'every' &&
    Array.isArray(condition.conditions) &&
    condition.conditions.length === 1 &&
    selfCondition(condition.conditions[0]))
/** Offline recognition of one explicitly bounded mechanism family, never runtime DSL evaluation. */
export function classifyInstantLiteral(definition) {
  if (!exact(definition, ['id', 'trigger', 'priority', 'apply', 'condition']))
    return { reason: 'unsupported definition fields' }
  if (typeof definition.id !== 'string' || !definition.id || !Number.isFinite(definition.priority))
    return { reason: 'invalid identity/priority' }
  const action = definition.apply
  if (
    !exact(action, ['type', 'target', 'value']) ||
    !['heal', 'addRage'].includes(action.type) ||
    !['self', 'opponent'].includes(action.target) ||
    !Number.isFinite(action.value)
  )
    return { reason: 'requires one literal heal/addRage action and a finite target preset' }
  const triggers = Array.isArray(definition.trigger) ? definition.trigger : [definition.trigger]
  if (!triggers.length || new Set(triggers).size !== triggers.length) return { reason: 'invalid triggers' }
  let condition
  if (selfCondition(definition.condition) && triggers.every(trigger => ['OnHit', 'OnMiss'].includes(trigger)))
    condition = 'selfUsesSkill'
  else if (
    exact(definition.condition, ['type']) &&
    definition.condition.type === 'petIsActive' &&
    triggers.length === 1 &&
    triggers[0] === 'TurnEnd'
  )
    condition = 'sourcePetIsActive'
  else return { reason: 'unsupported condition/trigger combination' }
  return {
    id: definition.id,
    triggers,
    priority: definition.priority,
    action: action.type,
    target: action.target,
    value: action.value,
    condition,
  }
}
const protectedIds = new Set(['effect_skill_heal_self_90_hp'])
export async function generateInstantLiterals({ check = false } = {}) {
  const records = [],
    rejected = [],
    ids = new Set()
  for (const file of ['effect_global', 'effect_ability', 'effect_emblem', 'effect_mark', 'effect_skill']) {
    const sourceFile = `packs/base/data/${file}.yaml`
    const definitions = parse(await readFile(sourceFile, 'utf8'), { merge: true })
    for (const [index, definition] of definitions.entries()) {
      if (ids.has(definition.id)) throw new Error(`Duplicate source ID: ${definition.id}`)
      ids.add(definition.id)
      if (!['heal', 'addRage'].includes(definition.apply?.type)) continue
      const recipe = classifyInstantLiteral(definition)
      const source = {
        id: definition.id,
        sourceFile,
        sourcePath: `/${index}`,
        definitionSha256: createHash('sha256').update(canonical(definition)).digest('hex'),
      }
      if (recipe.reason) {
        rejected.push({ ...source, reason: recipe.reason })
        continue
      }
      records.push({
        ...source,
        recipe,
        classification: 'U',
        status: protectedIds.has(recipe.id) ? 'handwritten-override-retained' : 'generated-candidate',
      })
    }
  }
  records.sort((a, b) => a.id.localeCompare(b.id, 'en'))
  rejected.sort((a, b) => a.id.localeCompare(b.id, 'en'))
  const candidates = records.filter(record => record.status === 'generated-candidate')
  const entries = candidates.map(({ recipe: r }) => {
    const target = r.target === 'self' ? 'owner' : 'context.battle.getOpponent(owner.owner!).activePet'
    const action =
      r.action === 'heal'
        ? `target.heal(new HealContext(context, context.source, target, ${r.value}))`
        : `target.addRage(new RageContext(context, target.owner!, 'effect', 'add', ${r.value}))`
    return `${JSON.stringify(r.id)}: defineNativeEffect({ id: ${JSON.stringify(r.id)} as effectId,
      triggers: [${r.triggers.map(trigger => `EffectTrigger.${trigger}`).join(', ')}], priority: ${r.priority}, when: ${r.condition},
      apply(context) { const owner = context.source.owner; if (!(owner instanceof Pet)) return; const target = ${target}; ${action} },
    })`
  })
  const code = `// Generated by scripts/effect-migration/instant-literals.mjs. Candidates only; no production registration.
import { EffectTrigger, type effectId } from '@arcadia-eternity/const'
import { HealContext, RageContext, UseSkillContext, type EffectContext } from '../context'
import { Pet } from '../pet'
import { SkillInstance } from '../skill'
import { MarkInstanceImpl } from '../mark'
import { defineNativeEffect } from '../content/native-effect'
function selfUsesSkill(context: EffectContext<EffectTrigger>): boolean {
  if (!(context.parent instanceof UseSkillContext)) return false
  return context.source instanceof SkillInstance ? context.source === context.parent.skill && context.source.owner === context.parent.pet
    : context.source instanceof MarkInstanceImpl && context.source.owner === context.parent.pet
}
function sourcePetIsActive(context: EffectContext<EffectTrigger>): boolean {
  return context.source.owner instanceof Pet && context.source.owner.isActive()
}
export const generatedInstantLiteralEffects = Object.freeze({${entries.join(',\n')}})
`
  const files = new Map([
    ['packages/battle/src/v4/official/instant-literals.generated.ts', code],
    [
      'docs/v4/validation/instant-literals-candidates.json',
      JSON.stringify(
        {
          formatVersion: 1,
          scope:
            'Single literal heal/addRage action with selfUseSkill or petIsActive only. Unsupported records are not emitted. All candidates remain U.',
          records,
          rejected,
        },
        null,
        2,
      ),
    ],
  ])
  for (const [path, raw] of files) {
    const output = await format(raw, { ...(await resolveConfig(path)), filepath: path })
    if (check) {
      if ((await readFile(path, 'utf8')) !== output) throw new Error(`Generated candidate drift: ${path}`)
    } else await writeFile(path, output)
  }
  return { generated: candidates.length, protected: records.length - candidates.length, rejected: rejected.length }
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Only --check is supported')
  console.log(JSON.stringify(await generateInstantLiterals({ check: process.argv.includes('--check') })))
}
